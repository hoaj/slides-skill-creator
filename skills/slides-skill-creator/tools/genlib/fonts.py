"""Put font files in a Brand pack: fonts/*.woff2, fonts.css and the manifest's `fonts` list.

The family, weight and style come from each file's own tables. A .ttf, .otf or .woff is converted
to .woff2, the only format the build reads. Running it again replaces the pack's font set, and
deletes only the files the old `fonts` list named. Needs fontTools and brotli.

The Generator does not check font licences: the maintainer must have the right to embed and
distribute the fonts.
"""
import pathlib
import re
import shutil

from .common import GenError, need, read_json, write_json, write_text

FORMATS = (".woff2", ".woff", ".ttf", ".otf")
HEADER = ("/* Generated by the slides-skill-creator fonts tool from the files in fonts/.\n"
          "   Run the tool again rather than editing this file. */\n")


def _read(path):
    ttlib = need("fontTools.ttLib", "fonttools brotli")
    try:
        font = ttlib.TTFont(str(path))
        name = font["name"]
        family = name.getDebugName(16) or name.getDebugName(1)
        sub = name.getDebugName(17) or name.getDebugName(2) or ""
        weight = font["OS/2"].usWeightClass
        italic = bool(font["OS/2"].fsSelection & 1) or bool(font["head"].macStyle & 2) \
            or "italic" in sub.lower()
    except Exception as e:
        raise GenError(f"{path}: not a readable font file ({type(e).__name__}: {e})")
    if not family:
        raise GenError(f"{path}: the font has no family name")
    return font, family, weight, "italic" if italic else "normal"


def _stack(value):
    """A font-family value split into its families, quotes kept."""
    return [part.strip() for part in value.split(",") if part.strip()]


def _bare(family):
    return family.strip().strip("\"'")


def _restack(tokens, token, family, drop):
    pattern = re.compile(r"(" + re.escape(token) + r"\s*:\s*)([^;]+)(;)")
    hit = pattern.search(tokens)
    if not hit:
        raise GenError(f"tokens.css has no {token} declaration to update")
    rest = [f for f in _stack(hit.group(2)) if _bare(f) not in drop]
    value = ", ".join([f'"{family}"'] + rest)
    return tokens[:hit.start()] + hit.group(1) + value + hit.group(3) + tokens[hit.end():], value


def build(pack_dir, sources, display=None, body=None):
    pack = pathlib.Path(pack_dir).resolve()
    manifest_path = pack / "brand.json"
    manifest = read_json(manifest_path)
    if not sources:
        raise GenError("give at least one font file with --src")
    sources = [pathlib.Path(s).resolve() for s in sources]
    for src in sources:
        if not src.is_file():
            raise GenError(f"font file not found: {src}")
        if src.suffix.lower() not in FORMATS:
            raise GenError(f"{src.name}: use .woff2, .woff, .ttf or .otf")

    faces, names = [], set()
    for src in sources:
        font, family, weight, style = _read(src)
        key = (family, weight, style)
        if any((f["family"], f["weight"], f["style"]) == key for f in faces):
            raise GenError(f"two files are {family} {weight} {style}; give each face once")
        file = f"fonts/{src.stem}.woff2"
        if file in names:
            raise GenError(f"two files would both be written as {file}; rename one")
        names.add(file)
        faces.append({"file": file, "family": family, "weight": weight, "style": style,
                      "_src": src, "_font": font})

    old = manifest.get("fonts") if isinstance(manifest.get("fonts"), list) else []
    old_files = {(f.get("file") if isinstance(f, dict) else f) for f in old}
    old_families = {f.get("family") for f in old if isinstance(f, dict) and f.get("family")}
    new_families = sorted({f["family"] for f in faces})
    for role, family in (("display", display), ("body", body)):
        if family and family not in new_families:
            raise GenError(f"--{role} {family!r} is not one of the fonts' families: {', '.join(new_families)}")

    folder = pack / "fonts"
    folder.mkdir(exist_ok=True)
    for face in faces:
        target = pack / face["file"]
        if face["_src"].suffix.lower() == ".woff2":
            if face["_src"] != target:
                shutil.copyfile(face["_src"], target)
        else:
            need("brotli", "brotli")
            face["_font"].flavor = "woff2"
            face["_font"].save(str(target))
    removed = []
    for file in sorted(old_files - names):
        if isinstance(file, str) and file.startswith("fonts/") and (pack / file).is_file():
            (pack / file).unlink()
            removed.append(file)

    faces.sort(key=lambda f: (f["family"], f["weight"], f["style"]))
    rules = [f'@font-face {{ font-family: "{f["family"]}"; font-style: {f["style"]}; '
             f'font-weight: {f["weight"]}; font-display: swap;\n'
             f'  src: url("{f["file"]}") format("woff2"); }}\n' for f in faces]
    write_text(pack / "fonts.css", HEADER + "".join(rules))
    manifest["fonts"] = [{k: f[k] for k in ("file", "family", "weight", "style")} for f in faces]
    write_json(manifest_path, manifest)

    stacks = {}
    if display or body:
        tokens = (pack / "tokens.css").read_text(encoding="utf-8")
        drop = old_families | set(new_families)
        for token, family in (("--font-display", display), ("--font-body", body)):
            if family:
                tokens, stacks[token] = _restack(tokens, token, family, drop)
        write_text(pack / "tokens.css", tokens)

    result = {"pack": str(pack), "fonts": manifest["fonts"], "families": new_families,
              "removed": removed, "written": ["fonts.css", "brand.json"] + [f["file"] for f in faces]}
    stray = sorted(p.name for p in folder.glob("*.woff2") if f"fonts/{p.name}" not in names)
    if stray:
        result["warning"] = (f"fonts/ also holds {', '.join(stray)}, which the build reads too. "
                             "Delete them unless they belong to the pack.")
    if stacks:
        result["stacks"] = stacks
        result["written"].append("tokens.css")
    unused = [f for f in new_families if not any(f in v for v in stacks.values())]
    if not stacks:
        result["next"] = ("set --font-display and --font-body in tokens.css to name these families "
                          "first, or run again with --display and --body")
    elif unused:
        result["next"] = f"no font stack names {', '.join(unused)} yet"
    return result
