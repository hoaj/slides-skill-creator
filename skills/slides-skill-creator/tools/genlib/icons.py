"""Build a Brand pack's icon-library.js from a folder of SVG files, and list the icons in icons.md.

Each icon is stored as {vb, inner}: its viewBox and inner markup, with hex fills and strokes set
to currentColor so icons follow the theme. Presentation attributes on the root <svg> (a stroke,
fill="none") would be lost, so they move onto a <g> around the inner markup. Only the generated
library ships; the source SVGs stay with the maintainer. Standard library only.
"""
import json
import pathlib
import re

from .common import GenError, write_text

VIEWBOX = re.compile(r'\bviewBox\s*=\s*"([^"]+)"')
ROOT = re.compile(r"<svg\b([^>]*)>(.*)</svg>", re.S)
ATTR = re.compile(r'([\w:-]+)\s*=\s*"([^"]*)"')
HEX_PAINT = re.compile(r'\b(fill|stroke)="#[0-9A-Fa-f]{3,8}"')
CARRIED = {"fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit",
           "fill-rule", "clip-rule", "opacity", "fill-opacity", "stroke-opacity"}
UNSAFE = re.compile(r"<script\b|<foreignObject\b|\son\w+\s*=|(?:xlink:)?href\s*=\s*\"(?!#)", re.I)
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
HEADER = "/* Generated by the slides-skill-creator icons tool. Run the tool again rather than editing. */\n"
GUIDE = """# {name} icons

`icon-library.js` holds the pack's icon set, generated by the Generator's icons tool. Keep the
set's source and licence in `licenses/`.

- Inline an icon as `<svg class="deck-icon" viewBox="..." fill="currentColor">...</svg>`, with the
  viewBox from the library.
- Icons inherit `--text`. Tint one with `--accent` by setting `color` on the icon.
- In edit mode, click an icon to swap or remove it.

Available: {names}.
"""
AVAILABLE = re.compile(r"^Available: .*$", re.M)


def normalise(svg, where):
    """(viewBox, inner markup) of one SVG file."""
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    if UNSAFE.search(svg):
        raise GenError(f"{where}: has a script, an event handler or a link to another file; "
                       "icons must be plain shapes")
    root = ROOT.search(svg)
    box = VIEWBOX.search(root.group(1)) if root else None
    if not root or not box:
        raise GenError(f"{where}: no <svg> with a viewBox")
    inner = root.group(2).strip()
    carried = [(k, v) for k, v in ATTR.findall(root.group(1)) if k in CARRIED]
    if carried:
        attrs = " ".join(f'{k}="{v}"' for k, v in carried)
        inner = f"<g {attrs}>{inner}</g>"
    inner = HEX_PAINT.sub(lambda m: f'{m.group(1)}="currentColor"', inner)
    return box.group(1), inner


def build(pack_dir, src):
    pack, src = pathlib.Path(pack_dir).resolve(), pathlib.Path(src).resolve()
    if not (pack / "brand.json").is_file():
        raise GenError(f"not a Brand pack (no brand.json): {pack}")
    if not src.is_dir():
        raise GenError(f"no such folder: {src}")
    files = sorted(src.glob("*.svg"))
    if not files:
        raise GenError(f"{src} holds no .svg files")
    icons = {}
    for path in files:
        name = path.stem.lower().replace("_", "-").replace(" ", "-")
        if not NAME.fullmatch(name):
            raise GenError(f"{path.name}: rename it to lowercase letters, digits and hyphens")
        if name in icons:
            raise GenError(f"two files are both named {name!r}")
        vb, inner = normalise(path.read_text(encoding="utf-8"), path.name)
        icons[name] = {"vb": vb, "inner": inner}
    icons = dict(sorted(icons.items()))
    write_text(pack / "icon-library.js",
               HEADER + "window.DeckIcons = " + json.dumps(icons, ensure_ascii=False) + ";\n")

    guide = pack / "icons.md"
    names = ", ".join(icons)
    if guide.is_file():
        text = guide.read_text(encoding="utf-8")
        if AVAILABLE.search(text):
            text = AVAILABLE.sub(lambda m: f"Available: {names}.", text, count=1)
        else:
            text = text.rstrip("\n") + f"\n\nAvailable: {names}.\n"
    else:
        from .pack import load
        text = GUIDE.format(name=load(pack).manifest.get("name", pack.name), names=names)
    write_text(guide, text)
    return {"pack": str(pack), "icons": len(icons), "names": list(icons),
            "written": ["icon-library.js", "icons.md"]}
